def normalize_name(name):
    """
    Normalize a player name for comparison
    
    Args:
        name (str): Player name to normalize
    
    Returns:
        str: Normalized name
    """
    if not name:
        return ""
    
    # Convert to lowercase
    normalized = name.lower()
    
    # Remove common suffixes and prefixes
    suffixes_to_remove = [' jr.', ' jr', ' sr.', ' sr', ' ii', ' iii', ' iv', ' v']
    for suffix in suffixes_to_remove:
        if normalized.endswith(suffix):
            normalized = normalized[:-len(suffix)]
    
    # Replace common abbreviations and variations
    replacements = {
        # Periods in initials
        '.': '',
        # Common name variations
        'kenneth': 'ken',
        'kenneth walker iii': 'ken walker iii',
        'ceedee': 'cd',
        'dj': 'dj',
        'd.j.': 'dj',
        'aj': 'aj',
        'a.j.': 'aj',
        'cj': 'cj',
        'c.j.': 'cj',
        'tj': 'tj',
        't.j.': 'tj',
        'jj': 'jj',
        'j.j.': 'jj',
        'kj': 'kj',
        'k.j.': 'kj',
        'rj': 'rj',
        'r.j.': 'rj',
        # Common contractions
        "d'andre": "dandre",
        "de'von": "devon",
        "ja'marr": "jamarr",
        "ja'lynn": "jalynn",
        "ka'imi": "kaimi",
        "ke'shawn": "keshawn",
        "n'keal": "nkeal",
        "o'cyrus": "ocyrus",
        # Team abbreviations
        " d/st": "",
        " dst": "",
        # Roman numerals
        " ii": "",
        " iii": "",
        " iv": "",
        " v": ""
    }
    
    for old, new in replacements.items():
        normalized = normalized.replace(old, new)
    
    # Remove extra whitespace
    normalized = ' '.join(normalized.split())
    
    return normalized

def similarity_score(name1, name2):
    """
    Calculate similarity between two names
    
    Args:
        name1 (str): First name
        name2 (str): Second name
    
    Returns:
        float: Similarity score between 0 and 1
    """
    return SequenceMatcher(None, name1, name2).ratio()

def find_matches(faab_names, sleeper_names, threshold=0.8):
    """
    Find matches between FAAB and Sleeper names
    
    Args:
        faab_names (list): Your FAAB player names
        sleeper_names (dict): Sleeper names (normalized -> original)
        threshold (float): Minimum similarity score for a match
    
    Returns:
        tuple: (exact_matches, fuzzy_matches, unmatched)
    """
    exact_matches = []
    fuzzy_matches = []
    unmatched = []
    
    for faab_name in faab_names:
        normalized_faab = normalize_name(faab_name)
        
        # Try exact match first
        if normalized_faab in sleeper_names:
            exact_matches.append({
                'faab_name': faab_name,
                'sleeper_name': sleeper_names[normalized_faab],
                'normalized_faab': normalized_faab,
                'normalized_sleeper': normalized_faab,
                'confidence': 'EXACT'
            })
            continue
        
        # Try fuzzy matching
        best_match = None
        best_score = 0
        
        for norm_sleeper, orig_sleeper in sleeper_names.items():
            score = similarity_score(normalized_faab, norm_sleeper)
            
            if score > best_score and score >= threshold:
                best_score = score
                best_match = {
                    'faab_name': faab_name,
                    'sleeper_name': orig_sleeper,
                    'normalized_faab': normalized_faab,
                    'normalized_sleeper': norm_sleeper,
                    'confidence': 'HIGH' if score >= 0.95 else 'MEDIUM' if score >= 0.85 else 'LOW',
                    'similarity_score': round(score, 3)
                }
        
        if best_match:
            fuzzy_matches.append(best_match)
        else:
            unmatched.append({
                'faab_name': faab_name,
                'normalized_faab': normalized_faab,
                'reason': 'No suitable match found'
            })
    
    return exact_matches, fuzzy_matches, unmatched

def create_mapping_csv(exact_matches, fuzzy_matches, unmatched, output_file='player_name_mapping.csv'):
    """
    Create a CSV file with the mapping results
    
    Args:
        exact_matches (list): Exact name matches
        fuzzy_matches (list): Fuzzy name matches  
        unmatched (list): Unmatched names
        output_file (str): Output CSV filename
    """
    with open(output_file, 'w', newline='', encoding='utf-8') as csvfile:
        fieldnames = ['faab_name', 'sleeper_name', 'confidence', 'similarity_score', 'notes', 'verified']
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        
        writer.writeheader()
        
        # Write exact matches
        for match in exact_matches:
            writer.writerow({
                'faab_name': match['faab_name'],
                'sleeper_name': match['sleeper_name'],
                'confidence': match['confidence'],
                'similarity_score': 1.0,
                'notes': 'Perfect match',
                'verified': 'YES'
            })
        
        # Write fuzzy matches
        for match in fuzzy_matches:
            writer.writerow({
                'faab_name': match['faab_name'],
                'sleeper_name': match['sleeper_name'],
                'confidence': match['confidence'],
                'similarity_score': match['similarity_score'],
                'notes': 'Fuzzy match - please verify',
                'verified': 'REVIEW'
            })
        
        # Write unmatched
        for item in unmatched:
            writer.writerow({
                'faab_name': item['faab_name'],
                'sleeper_name': '',
                'confidence': 'NONE',
                'similarity_score': 0.0,
                'notes': item['reason'],
                'verified': 'MANUAL'
            })

