def create_manual_mapping_template(unmatched, sleeper_names, output_file='manual_mapping_needed.csv'):
    """
    Create a template for manually mapping unmatched names
    
    Args:
        unmatched (list): Unmatched player names
        sleeper_names (dict): All Sleeper names for reference
        output_file (str): Output filename
    """
    with open(output_file, 'w', newline='', encoding='utf-8') as csvfile:
        fieldnames = ['faab_name', 'suggested_sleeper_name', 'confirmed_sleeper_name', 'notes']
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        
        writer.writeheader()
        
        # Add instructions row
        writer.writerow({
            'faab_name': 'INSTRUCTIONS: Fill in confirmed_sleeper_name column',
            'suggested_sleeper_name': 'Suggestions are provided where possible',
            'confirmed_sleeper_name': 'PUT_CORRECT_SLEEPER_NAME_HERE',
            'notes': 'Add any notes about the mapping'
        })
        
        for item in unmatched:
            # Try to find potential matches with lower threshold
            faab_normalized = normalize_name(item['faab_name'])
            suggestions = []
            
            for norm_sleeper, orig_sleeper in sleeper_names.items():
                score = similarity_score(faab_normalized, norm_sleeper)
                if score >= 0.5:  # Lower threshold for suggestions
                    suggestions.append((orig_sleeper, score))
            
            # Sort by score and take top suggestion
            suggestions.sort(key=lambda x: x[1], reverse=True)
            suggested = suggestions[0][0] if suggestions else "NOT_FOUND"
            
            writer.writerow({
                'faab_name': item['faab_name'],
                'suggested_sleeper_name': suggested,
                'confirmed_sleeper_name': '',
                'notes': ''
            })

def load_verified_mappings(csv_file):
    """
    Load verified mappings from CSV file
    
    Args:
        csv_file (str): Path to mapping CSV file
    
    Returns:
        dict: Dictionary mapping FAAB names to Sleeper names
    """
    mappings = {}
    
    try:
        with open(csv_file, 'r', encoding='utf-8') as csvfile:
            reader = csv.DictReader(csvfile)
            
            for row in reader:
                faab_name = row.get('faab_name', '').strip()
                sleeper_name = row.get('sleeper_name', '').strip()
                verified = row.get('verified', '').strip().upper()
                
                if faab_name and sleeper_name and verified == 'YES':
                    mappings[faab_name] = sleeper_name
        
        print(f"Loaded {len(mappings)} verified mappings from {csv_file}")
        return mappings
        
    except FileNotFoundError:
        print(f"Mapping file {csv_file} not found")
        return {}

